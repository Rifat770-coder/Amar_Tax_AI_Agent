import argparse
import json
import logging
import os
from pathlib import Path

from pydantic import ValidationError

from .database import load_database
from .engine import run_offline
from .models import Profile
from .report import render_markdown
from .settings import load_project_env

log = logging.getLogger(__name__)


def main() -> int:
    load_project_env()
    parser = argparse.ArgumentParser(description="Amar Tax — simulated assignment rules only")
    parser.add_argument("profile", type=Path, help="JSON profile path")
    parser.add_argument("--mode", choices=["offline", "crew"], default="offline")
    parser.add_argument("--output", type=Path, default=Path("output/report.md"))
    parser.add_argument("--strict-crew", action="store_true", help="Fail instead of using offline fallback")
    parser.add_argument("--rules-url", default=os.getenv("AMAR_TAX_RULES_URL"))
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    try:
        profile = Profile.model_validate_json(args.profile.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError, ValidationError) as exc:
        # Do not leave a plausible financial report for invalid input.
        log.error("Flagged — invalid profile input: %s", exc)
        return 2
    db, source = load_database(args.rules_url)
    if args.mode == "crew":
        try:
            from .crew import run_crew
            report = run_crew(profile, db, source)
        except Exception as exc:
            log.error("CrewAI execution failed (%s).", type(exc).__name__)
            if args.strict_crew:
                return 3
            log.warning("Falling back to Local DB deterministic workflow; no LLM interaction claimed.")
            report = run_offline(profile, db, source)
            report.mode = "offline fallback (CrewAI unavailable or validation failed)"
            report.review.status = "Flagged"
            report.review.findings.append("CrewAI execution failed; report generated by the deterministic Local DB fallback.")
    else:
        report = run_offline(profile, db, source)
    markdown = render_markdown(report, db)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown, encoding="utf-8")
    args.output.with_suffix(".json").write_text(report.model_dump_json(indent=2), encoding="utf-8")
    print(markdown)
    log.info("Saved %s and structured JSON", args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
